def translate_ui(text, lang="English"):
    """Translate UI static strings into target language."""
    if not lang or lang == "English" or text not in UI_DICTIONARY:
        return text
    
    translations = UI_DICTIONARY[text]
    return translations.get(lang, text)

def get_translated_scheme(scheme_dict, lang="English"):
    """Optionally translate scheme entity fields into target language if dictionary match exists."""
    if not lang or lang == "English":
        return scheme_dict
    
    scheme_name = scheme_dict.get('name')
    if scheme_name in SCHEME_TRANSLATIONS and lang in SCHEME_TRANSLATIONS[scheme_name]:
        t_data = SCHEME_TRANSLATIONS[scheme_name][lang]
        updated = dict(scheme_dict)
        updated['name'] = t_data.get('name', updated['name'])
        updated['description'] = t_data.get('description', updated['description'])
        updated['benefits'] = t_data.get('benefits', updated['benefits'])
        updated['eligibility'] = t_data.get('eligibility', updated['eligibility'])
        return updated
    return scheme_dict
